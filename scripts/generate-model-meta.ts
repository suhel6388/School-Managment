import fs from "node:fs";
import path from "node:path";
import { getDMMF } from "@prisma/internals";

/**
 * Prisma ORM 7 removed the runtime `Prisma.dmmf` export that the generic
 * resource engine used for model metadata. This script reads the legacy
 * single-tenant schema at build time and emits a plain TypeScript module with
 * the same information, so the application keeps its existing behaviour
 * without depending on Prisma internals at runtime.
 *
 * Run with: npm run db:generate:meta
 */
async function main() {
  const schemaArg = process.argv[2];
  const schemaPath = path.resolve(
    schemaArg ?? "prisma/schema.mysql.legacy.prisma",
  );
  const datamodel = fs.readFileSync(schemaPath, "utf8");
  const document = await getDMMF({ datamodel });

  const models: Record<string, unknown> = {};

  for (const model of document.datamodel.models) {
    const relations: Record<string, string> = {};

    for (const field of model.fields) {
      if (field.kind === "object") relations[field.name] = field.type;
    }

    models[model.name] = {
      fields: model.fields.map((field) => ({
        name: field.name,
        kind: field.kind,
        type: field.type,
        isList: field.isList,
        isRequired: field.isRequired,
        isId: field.isId,
        hasDefaultValue: field.hasDefaultValue,
        isUpdatedAt: field.isUpdatedAt ?? false,
        nativeType: field.nativeType,
      })),
      relations,
    };
  }

  const output = `// AUTO-GENERATED by scripts/generate-model-meta.ts — do not edit by hand.
// Source: ${path.relative(process.cwd(), schemaPath).replaceAll("\\", "/")}
// Regenerate with: npm run db:generate:meta

export type PrismaFieldMeta = {
  name: string;
  kind: string;
  type: string;
  isList: boolean;
  isRequired: boolean;
  isId: boolean;
  hasDefaultValue: boolean;
  isUpdatedAt: boolean;
  nativeType?: unknown;
};

export type PrismaModelMeta = {
  fields: PrismaFieldMeta[];
  relations: Record<string, string>;
};

export const prismaModelMeta: Record<string, PrismaModelMeta> = ${JSON.stringify(
    models,
    null,
    2,
  )};
`;

  const outputPath = path.resolve("src/lib/prisma-model-meta.ts");
  fs.writeFileSync(outputPath, output);
  console.log(
    `Generated ${outputPath} with ${document.datamodel.models.length} models.`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
